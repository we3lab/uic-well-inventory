# standard schema for all validation log entries
VALIDATION_LOG_COLUMNS = [
    "check_category", # validity or match
    "fields",         # list of fields involved in the check  
    "severity",       # low, medium, high
    "severity_desc",  # details on severity classification if applicable
    "observed",       # the value(s) observed in the dataset
    "expected",       # the value(s) expected based on reference data or other fields
    "message",        # a human-readable description of the issue
    "_source_file",   # the original source file for the row
    "_source_sheet",  # the original source sheet for the row
    "_source_row"    # the original source row for the row
]

##############################################################
### VALIDITY CHECKS
##############################################################
def validity_check(df, field, valid_set):
    """
    Checks that the values in a given field are all members of a valid set.

    Arguments:
        df : pd.DataFrame
            The DataFrame to check.
        field : str
            The name of the field to check.
        valid_set : list
            The set of valid values for the field.

    Returns:
    log_df : pd.DataFrame
        A DataFrame containing log entries for any rows that failed the check.
    
    """
    # isolate rows with relevant data
    relevant_fields = [field]
    has_data = df[relevant_fields].notna().all(axis=1)
    subset = df[has_data].copy().reset_index(drop=True)

    # if no rows have relevant data, return empty log
    if subset.empty:
        return pd.DataFrame(columns=VALIDATION_LOG_COLUMNS)

    # flag rows where the field value is not in the valid set
    flagged = subset[~subset[field].isin(valid_set)].copy()


    return pd.DataFrame({
        "check_category" : 'validity',
        "fields"         : field,
        "severity"       : 'high',
        "severity_desc"  : '',
        "observed"       : flagged[field].values,
        "expected"       : f'One of {valid_set}',
        "message"        : f"Field '{field}' contains values not in the valid set.",
        "_source_file"   : flagged["_source_file"].values,
        "_source_sheet"  : flagged["_source_sheet"].values,
        "_source_row"    : flagged["_source_row"].values
    })


##############################################################
### MATCHING CHECKS
##############################################################
def match_check(df, field1, field2, ref_map):
    """
    Checks that the values in field1 match the values in field2 based on a reference mapping.

    Arguments:
        df : pd.DataFrame
            The DataFrame to check.
        field1 : str
            The name of the first field to check.
        field2 : str
            The name of the second field to check.
        ref_map : dict
            A dictionary mapping values in field1 to expected values in field2.
            Should be generated by a reference table or other authoritative source.
    
    Returns:
        log_df : pd.DataFrame
            A DataFrame containing log entries for any rows that failed the check.
    """
    # isolate rows with relevant data
    relevant_fields = [field1, field2]
    has_data = df[relevant_fields].notna().all(axis=1)
    subset = df[has_data].copy().reset_index(drop=True)

    # if no rows have relevant data, return empty log
    if subset.empty:
        return pd.DataFrame(columns=VALIDATION_LOG_COLUMNS)

    # map field1 to expected values in field2 using the reference mapping
    subset[f'{field2}_from_{field1}'] = subset[field1].map(ref_map)

    # flag rows where field2_from_field1 does not match the actual value in field2
    flagged = subset[subset[f'{field2}_from_{field1}'] != subset[field2]].copy()

    # return log of flagged rows
    return pd.DataFrame({
        "check_category" : 'match',
        "fields"         : str(relevant_fields),
        "severity"       : 'high',
        "severity_desc"  : '',
        "observed"       : flagged[field2].values,
        "expected"       : flagged[f'{field2}_from_{field1}'].values,
        "message"        : f"Field '{field2}' does not match expected value based on '{field1}'.",
        "_source_file"   : flagged["_source_file"].values,
        "_source_sheet"  : flagged["_source_sheet"].values,
        "_source_row"    : flagged["_source_row"].values
    })

##############################################################
### COORDINATE CHECKS
##############################################################
def check_coords_in_county(df, refs):
    # isolate rows with relevant data
    relevant_fields = ["latitude", "longitude", "geoid"]
    has_data = df[relevant_fields].notna().all(axis=1)
    subset = df[has_data].copy().reset_index(drop=True)

    # if no rows have relevant data, return empty log
    if subset.empty:
        return pd.DataFrame(columns=VALIDATION_LOG_COLUMNS)

    # create a GeoDataFrame of lat/long points
    points = [
        Point(float(lo), float(la))
        for la, lo in zip(subset["latitude"], subset["longitude"])
    ]
    gdf = gpd.GeoDataFrame(subset, geometry=points, crs=TARGET_CRS)

    # create parallel gdf of county geometries corresponding to each row in gf
    us_counties = refs['us_counties'][['geoid','geometry']].copy()
    labeled_county_geoms = us_counties.set_index('geoid').loc[gdf['geoid']].reset_index()

    # convert to a projected CRS for distance calculation
    gdf = gdf.to_crs('EPSG:3857')
    us_counties = us_counties.to_crs('EPSG:3857')
    labeled_county_geoms = labeled_county_geoms.to_crs('EPSG:3857')

    # calculate distance from each point to corresponding county geometry
    gdf['distance_to_county'] = gdf.geometry.distance(labeled_county_geoms.geometry)

    # flag rows where distance to county is >0 
    flagged = gdf[gdf['distance_to_county'] > 0].copy()

    # if no rows have been flagged, return empty log
    if flagged.empty:
        return pd.DataFrame(columns=VALIDATION_LOG_COLUMNS)

    # otherwise, flag severity based on distance to labeled county
    # 0-10 km = low severity, 10-100 km = medium severity, >100 km = high severity
    flagged['severity'] = pd.cut(
        flagged['distance_to_county'],
        bins=[0, 10000, 100000, np.inf],
        labels=['low', 'medium', 'high']
    )
    flagged['severity_desc'] = flagged['severity'].map({
        'low' : '<10 km',
        'medium' : '10-100 km',
        'high' : '>100 km'
    })

    # identify county that the point is actually in (if any)
    actual_counties = gpd.sjoin(flagged, us_counties, how='left', predicate='within', rsuffix='actual')
    flagged['actual_county'] = actual_counties['geoid_actual']

    # return log of flagged rows
    return pd.DataFrame({
        "check_category" : 'coordinate',
        "fields"         : str(relevant_fields),
        "severity"       : flagged['severity'].values,
        "severity_desc"  : flagged['severity_desc'].values,
        "observed"       : flagged['geoid'].values,
        "expected"       : flagged['actual_county'].values,
        "message"        : f"Coordinates are not within the expected county.",
        "_source_file"   : flagged["_source_file"].values,
        "_source_sheet"  : flagged["_source_sheet"].values,
        "_source_row"    : flagged["_source_row"].values
    })


