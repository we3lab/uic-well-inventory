def run_all(df, refs):
    """
    Runs all validity and matching checks on the DataFrame.

    Arguments:
        df : pd.DataFrame
            The DataFrame to check.
        refs : dict
            A dictionary of reference DataFrames for various fields.
    """
    validation_logs = []

    ##### VALIDITY CHECKS #####
    # dictionary of valid sets for each field
    valid_set_dict = {
        # location information
        'epa_region': [f"Region {i}" for i in range(1, 11)],
        'geoid': refs['us_counties']['geoid'].unique(),
        'state_alpha': refs['us_states']['state_alpha'].unique(),

        # well class and subtype
        'well_class' : refs['well_subtypes']['well_class'].unique(),
        'well_subtype' : refs['well_subtypes']['well_subtype'].unique(),
        
        # _desc cols
        'well_id_desc': ['API Number', 'WACS ID', 'Permit Number', 'Well ID', 'Well Name', 'Site ID', 'Site Name'],
        'well_depth_ft_desc': ['LTD', 'DTD', 'MD', 'TVD', 'TIZ', 'UK'],
        'operator_desc': ['Company', 'Permittee', 'Lease Name', 'Site Name'],
        'date_desc': ['Status Date', 'Spud Date', 'Permit Date', 'Permit Expiration Date', 'Application Date', 'Completion Date', 'First Production Date']
    }

    # iterate through valid_set_dict and run validity_check for each field
    for field, valid_set in valid_set_dict.items():
        log_df = validity_check(df, field, valid_set)
        validation_logs.append(log_df)

    ##### MATCHING CHECKS #####
    match_ref_map_dict = {
        ('geoid', 'state_alpha'): dict(zip(refs['us_counties']['geoid'], refs['us_counties']['state_alpha'])),
        ('geoid', 'county_name'): dict(zip(refs['us_counties']['geoid'], refs['us_counties']['county_name'])),
        ('state_alpha', 'epa_region'): {state: region for region, states in EPA_REGION_TO_STATES.items() for state in states},
        ('well_subtype', 'well_class'): dict(zip(refs['well_subtypes']['well_subtype'], refs['well_subtypes']['well_class'])),
    }
    for (field1, field2), ref_map in match_ref_map_dict.items():
        log_df = match_check(df, field1, field2, ref_map)
        validation_logs.append(log_df)

    ##### COORDINATE CHECKS #####
    log_df = check_coords_in_county(df, refs)
    validation_logs.append(log_df)

    ##### COMBINE ALL CHECK LOGS #####
    # combine all validation logs into a single DataFrame
    combined_log_df = pd.concat(validation_logs, ignore_index=True)
    # sort by source_file
    combined_log_df = combined_log_df.sort_values(by=['_source_file', '_source_sheet', '_source_row']).reset_index(drop=True)

    return combined_log_df

